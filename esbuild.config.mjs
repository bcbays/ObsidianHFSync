import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { copyFileSync, existsSync, mkdirSync } from "fs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

// Everything Obsidian needs at runtime is bundled directly into this folder,
// so it can be copied as-is into <vault>/.obsidian/plugins/hf-sync/
const outDir = "dist/hf-sync";

/** Copies the static plugin assets (manifest + optional styles) into outDir. */
function copyStaticAssets() {
	mkdirSync(outDir, { recursive: true });
	copyFileSync("manifest.json", `${outDir}/manifest.json`);
	if (existsSync("styles.css")) {
		copyFileSync("styles.css", `${outDir}/styles.css`);
	}
}

const copyAssetsPlugin = {
	name: "copy-static-assets",
	setup(build) {
		build.onEnd(() => copyStaticAssets());
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: `${outDir}/main.js`,
	plugins: [copyAssetsPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
